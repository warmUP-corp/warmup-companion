#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn about_300_unique_emoji_in_8_categories() {
        let all: Vec<&str> = CATEGORIES
            .iter()
            .flat_map(|c| c.emoji.iter().copied())
            .collect();
        assert!((280..=330).contains(&all.len()), "{}", all.len());
        let mut sorted = all.clone();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), all.len());
        assert!(CATEGORIES.iter().all(|c| !c.emoji.is_empty()));
    }
}
